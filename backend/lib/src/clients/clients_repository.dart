import '../appointments/appointment_repository.dart';
import '../privacy/anonymized_identity.dart';

/// What [ClientsRepository.changeGuestPhone] found — and, for [changed]
/// alone, did (docs/design/phone-leftovers.md §8).
enum GuestPhoneOutcome {
  /// The card took the number, and this salon's manual bookings with it.
  changed,

  /// The card already had that number: nothing written.
  unchanged,

  /// No such card in this salon — a foreign id never resolves (T45).
  notFound,

  /// The card belongs to an account; its number is the account's.
  linked,

  /// Another card of this salon holds the number ([GuestPhoneChange.takenBy]).
  taken,
}

/// [client] is the card after the call ([GuestPhoneOutcome.changed] /
/// [GuestPhoneOutcome.unchanged]); [takenBy] the id of the card holding the
/// number ([GuestPhoneOutcome.taken] — null only if that card vanished in the
/// meantime).
typedef GuestPhoneChange = ({
  GuestPhoneOutcome outcome,
  Map<String, dynamic>? client,
  String? takenBy,
});

/// The salon client base (module `clients`, slice C1 —
/// docs/design/clients-c1.md). Each client is a `Map` in the `SalonClient`
/// DTO shape (docs/api/openapi.yaml): `{id, providerId, userId?, displayName,
/// phone?, tags, lastVisitAt?, createdAt}`. Notes are `{id, clientId,
/// authorAccountId, body, createdAt}`. Rows are DERIVED from bookings
/// (docs/modules/clients.md — "derived, not entered"): [upsertFromBooking]
/// keeps the base fresh; the 0024 migration backfills history.
abstract interface class ClientsRepository {
  /// Paginated salon-scoped list, `last_visit_at DESC NULLS LAST`.
  /// [query] matches the display name (case-insensitive substring) or the
  /// phone (digit-suffix); [tag] filters exact.
  Future<({List<Map<String, dynamic>> items, int total})> list(
    String providerId, {
    String? query,
    String? tag,
    required int page,
    required int pageSize,
  });

  /// Distinct tags across the salon's base (for the filter chips).
  Future<List<String>> tagsFor(String providerId);

  /// Scoped by provider — a foreign clientId resolves to null (404, no leak).
  Future<Map<String, dynamic>?> byId(String providerId, String clientId);

  Future<Map<String, dynamic>?> byPhone(String providerId, String phone);

  Future<Map<String, dynamic>?> byUserId(String providerId, String userId);

  /// Persist a new client row (id generated by the caller).
  Future<Map<String, dynamic>> create(Map<String, dynamic> client);

  /// Replace the tag set. Null when the client doesn't exist (scoped).
  Future<Map<String, dynamic>?> updateTags(
    String providerId,
    String clientId,
    List<String> tags,
  );

  /// Give a GUEST card (no account) the number [phone], and move this
  /// salon's manual bookings (`userId == 'manual'`) carrying its old number
  /// to the new one — in ONE transaction. A guest's history resolves by phone
  /// (`ClientsService._visitsOf`), so a card that moved alone would come out
  /// empty (docs/design/phone-leftovers.md §8). Never another salon's
  /// bookings, never a consumer's own (T45); a phone-less card adopts none.
  ///
  /// [phone] is already validated by the caller. A number another card of
  /// the salon holds is [GuestPhoneOutcome.taken] — a race lost on the
  /// `(provider_id, phone)` unique index included: it never throws.
  Future<GuestPhoneChange> changeGuestPhone(
    String providerId,
    String clientId,
    String phone,
  );

  /// Bump `lastVisitAt` if [visitAt] is later than the stored value.
  Future<void> touchLastVisit(
    String providerId,
    String clientId,
    DateTime visitAt,
  );

  // ---- Notes ---------------------------------------------------------------

  Future<Map<String, dynamic>> addNote(Map<String, dynamic> note);

  /// Newest first.
  Future<List<Map<String, dynamic>>> notesFor(String clientId);

  Future<Map<String, dynamic>?> noteById(String clientId, String noteId);

  Future<bool> deleteNote(String clientId, String noteId);

  /// Deletes EVERY client (and their notes) of [providerId]; returns the
  /// count. Same single-caller warning as
  /// `AppointmentRepository.wipeForProvider`: the demo reset only.
  Future<int> wipeForProvider(String providerId);

  // ---- Privacy (threat T48) ------------------------------------------------

  /// Deleted-account anonymization across EVERY salon: unlink `userId`, wipe
  /// name/phone; tags, notes and aggregates stay (no longer identifying).
  Future<void> anonymizeUser(String userId);
}

class InMemoryClientsRepository implements ClientsRepository {
  /// [appointments] is the twin [changeGuestPhone] moves a guest's history
  /// in — the Postgres twin reaches the `appointments` table in its own
  /// transaction. Typed as the in-memory twin on purpose: its `update`
  /// merges any field, where the Postgres one ignores `clientPhone`.
  InMemoryClientsRepository({InMemoryAppointmentRepository? appointments})
    : _appointments = appointments;

  final InMemoryAppointmentRepository? _appointments;
  final List<Map<String, dynamic>> _clients = [];
  final List<Map<String, dynamic>> _notes = [];

  @override
  Future<int> wipeForProvider(String providerId) async {
    final gone = _clients
        .where((c) => c['providerId'] == providerId)
        .map((c) => c['id'])
        .toSet();
    _notes.removeWhere((n) => gone.contains(n['clientId']));
    final before = _clients.length;
    _clients.removeWhere((c) => c['providerId'] == providerId);
    return before - _clients.length;
  }

  static String _digits(String s) => s.replaceAll(RegExp(r'[^0-9]'), '');

  @override
  Future<({List<Map<String, dynamic>> items, int total})> list(
    String providerId, {
    String? query,
    String? tag,
    required int page,
    required int pageSize,
  }) async {
    final q = query?.trim().toLowerCase();
    final qDigits = q == null ? '' : _digits(q);
    final filtered =
        _clients.where((c) => c['providerId'] == providerId).where((c) {
          if (tag != null && tag.isNotEmpty) {
            if (!(c['tags'] as List).contains(tag)) return false;
          }
          if (q == null || q.isEmpty) return true;
          final name = (c['displayName'] as String).toLowerCase();
          if (name.contains(q)) return true;
          final phone = c['phone'] as String?;
          return qDigits.length >= 2 &&
              phone != null &&
              _digits(phone).contains(qDigits);
        }).toList()..sort((a, b) {
          final la = a['lastVisitAt'] as String?;
          final lb = b['lastVisitAt'] as String?;
          if (la == null && lb == null) return 0;
          if (la == null) return 1; // NULLS LAST
          if (lb == null) return -1;
          return lb.compareTo(la);
        });
    final start = (page - 1) * pageSize;
    final items = start >= filtered.length
        ? <Map<String, dynamic>>[]
        : filtered.sublist(start, (start + pageSize).clamp(0, filtered.length));
    return (items: [for (final c in items) Map.of(c)], total: filtered.length);
  }

  @override
  Future<List<String>> tagsFor(String providerId) async {
    final tags = <String>{};
    for (final c in _clients) {
      if (c['providerId'] == providerId) {
        tags.addAll((c['tags'] as List).cast<String>());
      }
    }
    return tags.toList()..sort();
  }

  @override
  Future<Map<String, dynamic>?> byId(String providerId, String clientId) async {
    for (final c in _clients) {
      if (c['id'] == clientId && c['providerId'] == providerId) {
        return Map.of(c);
      }
    }
    return null;
  }

  @override
  Future<Map<String, dynamic>?> byPhone(String providerId, String phone) async {
    for (final c in _clients) {
      if (c['providerId'] == providerId && c['phone'] == phone) {
        return Map.of(c);
      }
    }
    return null;
  }

  @override
  Future<Map<String, dynamic>?> byUserId(
    String providerId,
    String userId,
  ) async {
    for (final c in _clients) {
      if (c['providerId'] == providerId && c['userId'] == userId) {
        return Map.of(c);
      }
    }
    return null;
  }

  @override
  Future<Map<String, dynamic>> create(Map<String, dynamic> client) async {
    _clients.add(Map.of(client));
    return Map.of(client);
  }

  @override
  Future<Map<String, dynamic>?> updateTags(
    String providerId,
    String clientId,
    List<String> tags,
  ) async {
    for (final c in _clients) {
      if (c['id'] == clientId && c['providerId'] == providerId) {
        c['tags'] = List<String>.of(tags);
        return Map.of(c);
      }
    }
    return null;
  }

  @override
  Future<GuestPhoneChange> changeGuestPhone(
    String providerId,
    String clientId,
    String phone,
  ) async {
    final appointments = _appointments;
    if (appointments == null) {
      // Moving the card without its bookings would strand the history.
      throw StateError(
        'InMemoryClientsRepository needs its appointments twin to change a '
        "guest's phone",
      );
    }
    // Read first: from the checks to the last write nothing yields, so no
    // other request lands in between — the twin of the row lock.
    final bookings = await appointments.listForProvider(providerId);
    Map<String, dynamic>? card;
    for (final c in _clients) {
      if (c['id'] == clientId && c['providerId'] == providerId) card = c;
    }
    if (card == null) {
      return (outcome: GuestPhoneOutcome.notFound, client: null, takenBy: null);
    }
    if (card['userId'] != null) {
      return (outcome: GuestPhoneOutcome.linked, client: null, takenBy: null);
    }
    final oldPhone = card['phone'] as String?;
    if (oldPhone == phone) {
      return (
        outcome: GuestPhoneOutcome.unchanged,
        client: Map.of(card),
        takenBy: null,
      );
    }
    for (final c in _clients) {
      if (c['providerId'] == providerId &&
          c['phone'] == phone &&
          c['id'] != clientId) {
        return (
          outcome: GuestPhoneOutcome.taken,
          client: null,
          takenBy: c['id'] as String,
        );
      }
    }
    card['phone'] = phone;
    // `update` has no await inside: each call writes before it returns its
    // future, so the bookings move in the same synchronous stretch as the
    // card. A phone-less card adopts no one (`null == null` would sweep up
    // every phone-less walk-in).
    await Future.wait([
      if (oldPhone != null)
        for (final a in bookings)
          if (a['userId'] == 'manual' && a['clientPhone'] == oldPhone)
            appointments.update(a['id'] as String, {'clientPhone': phone}),
    ]);
    return (
      outcome: GuestPhoneOutcome.changed,
      client: Map.of(card),
      takenBy: null,
    );
  }

  @override
  Future<void> touchLastVisit(
    String providerId,
    String clientId,
    DateTime visitAt,
  ) async {
    for (final c in _clients) {
      if (c['id'] == clientId && c['providerId'] == providerId) {
        final current = c['lastVisitAt'] as String?;
        final iso = visitAt.toUtc().toIso8601String();
        if (current == null || current.compareTo(iso) < 0) {
          c['lastVisitAt'] = iso;
        }
      }
    }
  }

  @override
  Future<Map<String, dynamic>> addNote(Map<String, dynamic> note) async {
    _notes.add(Map.of(note));
    return Map.of(note);
  }

  @override
  Future<List<Map<String, dynamic>>> notesFor(String clientId) async {
    return [
      for (final n in _notes.reversed)
        if (n['clientId'] == clientId) Map.of(n),
    ];
  }

  @override
  Future<Map<String, dynamic>?> noteById(String clientId, String noteId) async {
    for (final n in _notes) {
      if (n['id'] == noteId && n['clientId'] == clientId) return Map.of(n);
    }
    return null;
  }

  @override
  Future<bool> deleteNote(String clientId, String noteId) async {
    final before = _notes.length;
    _notes.removeWhere((n) => n['id'] == noteId && n['clientId'] == clientId);
    return _notes.length < before;
  }

  @override
  Future<void> anonymizeUser(String userId) async {
    for (final c in _clients) {
      if (c['userId'] == userId) {
        c['userId'] = null;
        c['displayName'] = anonymousClientLabel;
        c['phone'] = null;
      }
    }
  }
}
