// Writes `lib/src/search_fold_table.dart`: every character PostgreSQL's
// `unaccent()` changes, and what it becomes, read from a real PostgreSQL.
//
//   DATABASE_URL=postgres://…/a_throwaway_db dart run tool/search_fold_table.dart
//
// **Why a generated table.** A search ignores accents on Postgres through
// `lower(unaccent(…))`, and the in-memory twin must fold exactly the same way
// or the two answer differently (docs/design/consumer-search.md §3, A4-api,
// decision 228). Copying the table from the database is the only way to get
// "the same"; a hand-written one drifts on the first character nobody
// thought of. The Postgres suite compares the two on every character of the
// Basic Multilingual Plane, so a table that no longer matches the database's
// fails CI.
//
// Point DATABASE_URL at a local or throwaway database: this creates the
// `unaccent` extension there if it is missing. Rerun it when production moves
// to another PostgreSQL major, then let the suite confirm.
import 'dart:io';

import 'package:myweli_backend/src/db/database.dart';

Future<void> main() async {
  final url = Platform.environment['DATABASE_URL'];
  if (url == null || url.isEmpty) {
    stderr.writeln('Set DATABASE_URL to a local or throwaway database.');
    exitCode = 64;
    return;
  }
  final pool = createPool(url);
  try {
    await pool.execute('CREATE EXTENSION IF NOT EXISTS unaccent');
    final version =
        (await pool.execute('SHOW server_version')).first.first! as String;
    // Every code point except NUL and the surrogates, which are not
    // characters and which `chr` refuses.
    final rows = await pool.execute(
      'SELECT n, unaccent(chr(n)) FROM generate_series(1, 1114111) n '
      'WHERE n NOT BETWEEN 55296 AND 57343 AND unaccent(chr(n)) <> chr(n) '
      'ORDER BY n',
    );
    final out = StringBuffer()
      ..writeln('// GENERATED by tool/search_fold_table.dart from PostgreSQL')
      ..writeln(
        '// ${version.split(' ').first}\'s `unaccent()`: do not edit by hand.',
      )
      ..writeln('//')
      ..writeln('// docs/design/consumer-search.md §3 (A4-api, decision 228).')
      ..writeln('// The Postgres suite holds it to the database it runs on.')
      ..writeln()
      ..writeln('/// Every code point PostgreSQL\'s `unaccent()` changes, and')
      ..writeln('/// what it becomes (often nothing: a combining accent is')
      ..writeln('/// dropped). `foldSearchText` applies it, then lower-cases,')
      ..writeln('/// as `lower(unaccent(…))` does.')
      ..writeln('const Map<int, String> kUnaccentFold = {');
    for (final row in rows) {
      final n = row[0]! as int;
      final to = row[1]! as String;
      out.writeln(
        '  0x${n.toRadixString(16).toUpperCase().padLeft(4, '0')}: '
        '${_literal(to)},',
      );
    }
    out.writeln('};');
    final file = File('lib/src/search_fold_table.dart')
      ..writeAsStringSync(out.toString());
    stdout.writeln(
      '${rows.length} entries → ${file.path} (PostgreSQL $version)',
    );
  } finally {
    await pool.close();
  }
}

/// [s] as a single-quoted Dart literal, ASCII only: anything else is a
/// `\u{…}` escape, so the file shows exactly which code point it holds.
String _literal(String s) {
  final b = StringBuffer("'");
  for (final r in s.runes) {
    if (r == 0x27 || r == 0x5C || r == 0x24) {
      b.write('\\${String.fromCharCode(r)}');
    } else if (r >= 0x20 && r < 0x7F) {
      b.writeCharCode(r);
    } else {
      b.write('\\u{${r.toRadixString(16).toUpperCase()}}');
    }
  }
  b.write("'");
  return b.toString();
}
