/// The salon page's test photo: a room drawn from numbers (docs/design/web-swiss-salon.md
/// §1.1 item 9, §1.9, §1.10).
///
/// **Why this exists.** The cover's new shape asks a computer for a smaller file (828w in
/// place of 1920w at 1280), and that only shows in bytes when the source is wider than
/// 828 px: Next's optimizer never enlarges. The stub's photos are 64×48, and the demo rooms
/// cannot be published (their licence is unknown, BACKLOG 37). So the manual LCP runs and
/// the PR's before-and-after pictures use this photo, and no other.
///
/// **What it is.** An upright 2448×3264 room (3:4, an 8-megapixel phone's shape) at a real
/// camera's weight: a ceiling with three pendant lights, three mirrors over a counter with
/// bottles, three black chairs, a cabinet, a plank floor and a plant, under a camera's grain
/// and a slight vignette. Ticks on both edges mark every tenth of the height, longer at the
/// half, so a picture of the cover shows which band of the photo it keeps (at 3:2 and
/// `object-subject` an upright 3:4 photo keeps 10%–60%). **No person, no face, nothing
/// generated by a model:** every pixel is arithmetic, so the bytes need no licence.
///
/// **Deterministic.** One seeded generator, no clock, no `Math.random`: the same command
/// gives the same bytes on any machine with this lockfile (tests/test-photo.test.ts pins a
/// small render's hash). `jpeg-js` is declared at exactly 0.4.4 in `package.json`, the copy
/// `@lhci/cli`'s Lighthouse already locked, so nothing new is downloaded, and a bump of
/// Lighthouse cannot move or drop the encoder this hash depends on.
///
/// **Never committed.** It writes to `tool/out/`, and `web/.gitignore` ignores every JPEG
/// under `web/`, wherever a path passed here puts it:
///
///     node tool/test-photo.mjs                 # → tool/out/salon-test-photo.jpg
///     node tool/test-photo.mjs /some/where.jpg
///
/// For the LCP runs it is served as the stub's `p1.jpg`, through a rewrite of
/// `https://cdn.stub/` to a local file server, so the Next optimizer reads real bytes.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import jpeg from 'jpeg-js';

export const WIDTH = 2448;
export const HEIGHT = 3264;
export const QUALITY = 92;
export const SEED = 20261106;

/// mulberry32: a 32-bit seeded generator, uniform in [0, 1).
function generator(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/// Smooth value noise over the unit square: random values on a lattice, eased between.
function valueNoise(random, cellsX, cellsY) {
  const lattice = new Float32Array((cellsX + 1) * (cellsY + 1));
  for (let i = 0; i < lattice.length; i++) lattice[i] = random();
  const ease = (t) => t * t * (3 - 2 * t);
  return (u, v) => {
    const x = Math.min(u, 0.999999) * cellsX;
    const y = Math.min(v, 0.999999) * cellsY;
    const i = Math.floor(x);
    const j = Math.floor(y);
    const fx = ease(x - i);
    const fy = ease(y - j);
    const row = cellsX + 1;
    const a = lattice[j * row + i];
    const b = lattice[j * row + i + 1];
    const c = lattice[(j + 1) * row + i];
    const d = lattice[(j + 1) * row + i + 1];
    return a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy;
  };
}

const mix = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
const clamp = (x) => (x < 0 ? 0 : x > 255 ? 255 : x);

/// The room, in RGBA, as `jpeg-js` takes it. Every shape is placed in fractions of the
/// frame, so a small render is the same room, smaller (the test draws one).
export function drawTestPhoto({ width = WIDTH, height = HEIGHT, seed = SEED } = {}) {
  const random = generator(seed);
  const plaster = valueNoise(random, 36, 48);
  const blotch = valueNoise(random, 9, 12);
  const grainField = valueNoise(random, 640, 860);
  const leaves = valueNoise(random, 28, 60);
  const wood = valueNoise(random, 12, 220);

  const lights = [0.2, 0.5, 0.8];
  const mirrors = [0.2, 0.5, 0.8];
  const chairs = [0.2, 0.5, 0.8];
  // Bottles between and under the mirrors, each its own colour and height.
  const bottles = [];
  for (let k = 0; k < 18; k++) {
    const u = 0.06 + k * 0.05 + random() * 0.01;
    bottles.push({
      u,
      w: 0.012 + random() * 0.01,
      top: 0.505 + random() * 0.03,
      colour: [60 + random() * 170, 40 + random() * 150, 40 + random() * 160],
    });
  }
  const planks = [];
  for (let k = 0; k < 40; k++) planks.push({ seam: random(), tone: random() });

  const data = Buffer.alloc(width * height * 4);
  const tickRows = new Set();
  for (let t = 1; t < 10; t++) {
    const centre = Math.round((t / 10) * height);
    const half = Math.max(1, Math.round(height * 0.0012));
    for (let y = centre - half; y <= centre + half; y++) tickRows.add(y);
  }

  for (let y = 0; y < height; y++) {
    const v = y / height;
    for (let x = 0; x < width; x++) {
      const u = x / width;
      let c;

      if (v < 0.1) {
        // The ceiling, lighter towards the lights, with a cove line at its foot.
        c = mix([238, 233, 224], [222, 214, 202], v / 0.1);
        if (v > 0.094) c = mix(c, [150, 135, 118], 0.6);
      } else if (v < 0.62) {
        // The wall: warm plaster, uneven.
        c = mix([206, 176, 150], [186, 152, 126], (v - 0.1) / 0.52);
        const p = plaster(u, v) - 0.5;
        const b = blotch(u, v) - 0.5;
        c = [c[0] + p * 22 + b * 18, c[1] + p * 20 + b * 14, c[2] + p * 18 + b * 10];
      } else if (v < 0.8) {
        // A cabinet under the counter: panels with grooves between them.
        const panel = (u * 8) % 1;
        c = [118, 92, 70];
        if (panel < 0.02 || panel > 0.98) c = [64, 46, 34];
        const g = wood(u, v) - 0.5;
        c = [c[0] + g * 30, c[1] + g * 22, c[2] + g * 16];
      } else {
        // The floor: staggered planks with their grain.
        const row = Math.floor((v - 0.8) / 0.025);
        const plank = planks[row % planks.length];
        const along = (u + plank.seam) % 0.33;
        const tone = 0.75 + plank.tone * 0.35;
        c = [150 * tone, 112 * tone, 78 * tone];
        const g = wood(u * 0.2 + row * 0.07, v) - 0.5;
        c = [c[0] + g * 46, c[1] + g * 34, c[2] + g * 22];
        if (along < 0.004 || ((v - 0.8) / 0.025) % 1 < 0.06) c = mix(c, [52, 36, 26], 0.7);
        // Darker towards the camera.
        c = mix(c, [40, 30, 22], (v - 0.8) * 1.2);
      }

      // Three mirrors in brass frames, the room behind them cooler and blurred.
      for (const m of mirrors) {
        const left = m - 0.1;
        const right = m + 0.1;
        if (u >= left && u <= right && v >= 0.2 && v <= 0.52) {
          const frame = 0.012;
          if (u < left + frame || u > right - frame || v < 0.2 + frame || v > 0.52 - frame) {
            c = mix([142, 112, 66], [96, 74, 44], (v - 0.2) / 0.32);
          } else {
            const d = ((u - left) + (v - 0.2)) / 0.52;
            c = mix([196, 206, 212], [120, 134, 148], d);
            const streak = Math.abs(((u - left) * 3 - (v - 0.2) * 1.4) % 0.18 - 0.09);
            if (streak < 0.012) c = mix(c, [236, 240, 242], 0.35);
          }
        }
      }

      // The counter's edge, dark walnut with grain.
      if (v >= 0.55 && v < 0.6) {
        const g = Math.sin(u * 180 + wood(u, v) * 9) * 0.5;
        c = [88 + g * 14, 58 + g * 10, 38 + g * 8];
        if (v < 0.555) c = mix(c, [150, 120, 92], 0.5);
      }

      // Bottles standing on the counter.
      for (const bottle of bottles) {
        if (u >= bottle.u && u <= bottle.u + bottle.w && v >= bottle.top && v < 0.55) {
          const shade = 0.7 + 0.5 * Math.sin(((u - bottle.u) / bottle.w) * Math.PI);
          c = [bottle.colour[0] * shade, bottle.colour[1] * shade, bottle.colour[2] * shade];
        }
      }

      // Three black chairs in front of the counter: back, seat, column and foot.
      for (const ch of chairs) {
        const du = u - ch;
        const inBack = Math.abs(du) < 0.07 && v >= 0.58 && v < 0.7;
        const inSeat = Math.abs(du) < 0.085 && v >= 0.7 && v < 0.74;
        const inColumn = Math.abs(du) < 0.012 && v >= 0.74 && v < 0.84;
        const inFoot = Math.abs(du) < 0.06 && v >= 0.84 && v < 0.855;
        if (inBack || inSeat) {
          const sheen = Math.max(0, 1 - Math.abs(du + 0.03) / 0.05) * 0.35;
          c = mix([34, 31, 30], [120, 116, 112], sheen);
        } else if (inColumn || inFoot) {
          c = mix([150, 150, 152], [70, 70, 74], Math.abs(du) / 0.06);
        }
      }

      // A tall plant at the right edge, from a pot on the floor.
      if (u > 0.9 && v > 0.38 && v < 0.82) {
        const cx = 0.955 + Math.sin(v * 22) * 0.012;
        const spread = 0.05 * Math.sin(((v - 0.38) / 0.44) * Math.PI);
        if (Math.abs(u - cx) < spread && leaves(u, v) > 0.42) {
          const l = leaves(u * 3, v * 2);
          c = [40 + l * 40, 92 + l * 70, 46 + l * 30];
        }
      }
      if (u > 0.92 && u < 0.99 && v >= 0.82 && v < 0.9) c = [170, 90, 60];

      // The pendant lights: a cord, a shade, and a warm glow on the wall and ceiling.
      for (const lx of lights) {
        const du = u - lx;
        if (Math.abs(du) < 0.0015 && v < 0.07) c = [30, 30, 30];
        if (Math.abs(du) < 0.05 - (v - 0.07) * 0.2 && v >= 0.07 && v < 0.12) {
          c = mix([60, 52, 40], [30, 26, 22], (v - 0.07) / 0.05);
        }
        const dy = (v - 0.13) * (height / width);
        const glow = Math.exp(-(du * du + dy * dy) / 0.004);
        c = [c[0] + glow * 70, c[1] + glow * 58, c[2] + glow * 30];
      }

      // Ticks on both edges at every tenth of the height, longer at the half.
      if (tickRows.has(y)) {
        const long = Math.abs(v - 0.5) < 0.01;
        const reach = long ? 0.045 : 0.025;
        if (u < reach || u > 1 - reach) c = [250, 250, 250];
      }

      // The camera: a slight vignette and its grain, coarse and fine.
      const r2 = (u - 0.5) * (u - 0.5) + (v - 0.5) * (v - 0.5) * 0.6;
      const vignette = 1 - r2 * 0.55;
      const grain = (grainField(u, v) - 0.5) * 9 + (random() - 0.5) * 16;
      const i = (y * width + x) * 4;
      data[i] = clamp(c[0] * vignette + grain);
      data[i + 1] = clamp(c[1] * vignette + grain * 0.9);
      data[i + 2] = clamp(c[2] * vignette + grain * 1.1);
      data[i + 3] = 255;
    }
  }
  return { width, height, data };
}

/// The JPEG's bytes. Baseline, no metadata: the pixels are upright, with no EXIF turn.
export function encodeTestPhoto(image, quality = QUALITY) {
  return jpeg.encode(image, quality).data;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  const out = resolve(process.argv[2] ?? resolve(here, 'out/salon-test-photo.jpg'));
  const bytes = encodeTestPhoto(drawTestPhoto());
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, bytes);
  const sha = createHash('sha256').update(bytes).digest('hex');
  console.log(`${out}\n${WIDTH}×${HEIGHT}, ${bytes.length} bytes, sha256 ${sha}`);
}
