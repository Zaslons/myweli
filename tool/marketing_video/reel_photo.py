"""The owner's two pictures (storyboard amendment A1, 2026-10-18).
Design: docs/design/pro-marketing-reel.md §2 and §9.

  the files   build/marketing/photos/ in the main checkout (ignored by git,
              never copied into the repository): hook-owner-notebook.webp
              (S1) and closing-stylist-braiding.webp (S7b), 941 x 1672,
              AI-generated by the owner. Each must have the sha256 the
              storyboard quotes, or the build stops; `prepare` decodes
              them once into the work folder.
  placement   a uniform scale, never a stretch. The base scale is the
              least that fills the frame's width (S1: 1080 / 941) or the
              whole frame (S7b: 1920 / 1672); the push-in multiplies it
              (1.00 -> 1.04 and 1.00 -> 1.02, linear) about one point of
              the picture held still in the frame — S1's stroke start on
              the notebook, the top of the S7b stylist's bun (R4: her bun
              stays still under the caption). Nothing is enlarged more
              than that.
  drawing     the picture resampled straight into the frame (Lanczos, a
              fractional box, like the card); S1's picture ends at y ~1600
              and fades into black over its last 160 px; a black gradient
              from the top (S1 72 %, S7b 62 %, held to a line, then
              easing to 0) carries the white words.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from PIL import Image

import reel_plan as plan


def smoothstep(e0: float, e1: float, x: np.ndarray) -> np.ndarray:
    u = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return u * u * (3 - 2 * u)


@dataclass(frozen=True)
class Placement:
    scale: float          # frame px per picture px
    ox: float             # where the picture's (0, 0) lands
    oy: float
    base: float           # the least scale that fills what the spec fills
    size: tuple[int, int]

    def box(self) -> tuple[float, float, float, float]:
        w, h = self.size
        return (self.ox, self.oy, self.ox + w * self.scale, self.oy + h * self.scale)

    def at(self, x: float, y: float) -> tuple[float, float]:
        return self.ox + x * self.scale, self.oy + y * self.scale


def base_scale(spec: dict, frame: tuple[int, int]) -> float:
    w, h = plan.PHOTOS[spec["photo"]]["size"]
    W, H = frame
    return W / w if spec["fill"] == "width" else max(W / w, H / h)


def push(spec: dict, t: float) -> float:
    z1, t0, t1 = spec["push"]
    return 1 + (z1 - 1) * min(1.0, max(0.0, (t - t0) / (t1 - t0)))


def placement(spec: dict, t: float, frame: tuple[int, int]) -> Placement:
    """Where the picture sits at time t: its base scale times the push-in,
    about the anchor (a point of the picture held still in the frame)."""
    w, h = plan.PHOTOS[spec["photo"]]["size"]
    W, H = frame
    base = base_scale(spec, frame)
    ax, ay = spec["anchor_src"]
    ox0 = (W - w * base) / 2                       # centred in width at the base scale
    oy0 = (H - h * base) / 2
    fx = ox0 + ax * base
    fy = spec["anchor_y"] if spec["anchor_y"] is not None else oy0 + ay * base
    s = base * push(spec, t)
    return Placement(s, fx - ax * s, fy - ay * s, base, (w, h))


def gradient(spec: dict, height: int) -> np.ndarray:
    """The black over the picture, per row: `top` down to y0, easing to 0
    at y1."""
    top, y0, y1 = spec["gradient"]
    ys = np.arange(height, dtype=np.float32) + 0.5
    return (top * (1 - smoothstep(y0, y1, ys))).astype(np.float32)


def render(picture: Image.Image, pl: Placement, spec: dict, frame: tuple[int, int]) -> np.ndarray:
    """The picture in the frame as float RGB (black where it does not
    reach), its bottom fade and the gradient applied."""
    W, H = frame
    out = np.zeros((H, W, 3), np.float32)
    x0, y0, x1, y1 = pl.box()
    ya, yb = max(0, math.floor(y0)), min(H, math.ceil(y1))
    if yb > ya:
        s = pl.scale
        box = ((0 - pl.ox) / s, (ya - pl.oy) / s, (W - pl.ox) / s, min((yb - pl.oy) / s, picture.height))
        region = picture.resize((W, yb - ya), Image.LANCZOS, box=box)
        a = np.asarray(region, np.float32)
        ys = np.arange(ya, yb, dtype=np.float32) + 0.5
        cover = np.clip(np.minimum(ys - y0, y1 - ys), 0.0, 1.0)          # the picture's own edge rows
        fade = spec.get("fade_bottom") or 0
        if fade:
            cover = cover * (1 - smoothstep(y1 - fade, y1, ys))
        out[ya:yb] = a * cover[:, None, None]
    g = gradient(spec, H)
    return out * (1 - g[:, None, None])


def sha256_ok(path: Path, key: str) -> bool:
    h = hashlib.sha256(path.read_bytes()).hexdigest()
    return h == plan.PHOTOS[key]["sha256"]


def prepare(photos: Path, work: Path) -> dict:
    """Check the pictures against the storyboard's sha256 and decode them
    into `work/photos/<key>.png`. Returns facts for the build record."""
    out = work / "photos"
    out.mkdir(parents=True, exist_ok=True)
    facts = {}
    for key, p in plan.PHOTOS.items():
        src = photos / p["file"]
        if not src.exists():
            plan.die(f"missing {src} — --photos is the main checkout's build/marketing/photos")
        if not sha256_ok(src, key):
            plan.die(f"{src} is not the picture the storyboard approved (sha256 {p['sha256'][:12]}…)")
        im = Image.open(src).convert("RGB")
        if im.size != tuple(p["size"]):
            plan.die(f"{src} is {im.size}, the storyboard places a {p['size']} picture")
        im.save(out / f"{key}.png", "PNG", compress_level=1)
        facts[key] = {"file": p["file"], "sha256": p["sha256"], "size": list(im.size)}
    return facts


def load(work: Path, key: str) -> Image.Image:
    return Image.open(work / "photos" / f"{key}.png").convert("RGB")
